function ncpInputs = updateNcpInitialGuess(ncpInputs, ...
    precalInputs, optimizedInitialGuess)
[values, precalInputs] = ...
    makeMuscleTendonLengthInitializationValuesAsStruct( ...
    optimizedInitialGuess, precalInputs);
% MTLI keeps muscles in model order and NCP in synergy group order, so
% match them by name. nonMtpEntries indexes NCP muscles and precalEntries
% the same muscles in MTLI
[nonMtpEntries, precalIndex] = ismember( ...
    ncpInputs.muscleTendonColumnNames, precalInputs.muscleNames);
if isfield(ncpInputs, 'mtpActivationsColumnNames')
    nonMtpEntries = nonMtpEntries & ~ismember( ...
        ncpInputs.muscleTendonColumnNames, ...
        ncpInputs.mtpActivationsColumnNames);
end
precalEntries = precalIndex(nonMtpEntries);
if precalInputs.useAbsoluteLengths
    ncpInputs.optimalFiberLength(nonMtpEntries) = ...
        precalInputs.optimalFiberLength(precalEntries);
    ncpInputs.tendonSlackLength(nonMtpEntries) = ...
        precalInputs.tendonSlackLength(precalEntries);
else
    ncpInputs.optimalFiberLength(nonMtpEntries) = ...
        precalInputs.optimalFiberLength(precalEntries) ...
        .* values.optimalFiberLengthScaleFactors(precalEntries);
    ncpInputs.tendonSlackLength(nonMtpEntries) = ...
        precalInputs.tendonSlackLength(precalEntries) .* ...
        values.tendonSlackLengthScaleFactors(precalEntries);
end
newMaxIsometricForce = getMaxIsometricForce(precalInputs, values);
ncpInputs.maxIsometricForce(nonMtpEntries) = ...
    newMaxIsometricForce(precalEntries);
end

